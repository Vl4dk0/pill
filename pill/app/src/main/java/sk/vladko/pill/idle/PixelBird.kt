/** The pixel bird scene: shares the pixel sizing, hole avoidance and walking span, drawn from crisp pixel sprites. */
internal class PixelBirdScene(
    val w: Float,
    val h: Float,
    val hole: Rect?,
    fixedUnit: Float? = null,
) : PetScene {
    private val room = if (hole == null) w else max(hole.left, w - hole.right)

    val pix =
        if (fixedUnit != null) {
            max(1, fixedUnit.toInt())
        } else if (hole == null && w < h * 3f) {
            max(1, floor(min(h, w) * 0.98f / GRID).toInt())
        } else {
            max(1, min(floor(h * 0.95f / GRID).toInt(), min(floor(w * 0.4f / GRID).toInt(), floor(room / GRID).toInt())))
        }

    override val unit get() = pix.toFloat()
    private val edge = min(h * 0.28f, max(0f, (room - GRID * pix) / 2f))
    private val box = (GRID * pix).toFloat()

    private val leftEnd =
        if (hole == null || hole.left - edge >= box) edge else min(hole.right + pix * 2f, w - edge - box)
    private val rightEnd =
        if (hole == null || w - edge - hole.right >= box) w - edge - box else max(hole.left - pix * 2f - box, leftEnd)
    private val span = max(0f, rightEnd - leftEnd)

    private val top = min((h - box) * 0.7f, h - box - h * 0.04f)
    private val holePath = Path().apply { hole?.let { addOval(it) } }

    override val canWalk = span >= 2 * pix

    override val holeX = if (hole == null || span <= 0f) 0.5f else ((hole.center.x - box / 2f - leftEnd) / span).coerceIn(0f, 1f)

    override val drawsRoam get() = true

    private fun left(x: Float) = leftEnd + span * x

    override fun middle(x: Float) = left(x) + box / 2f

    private val rigRasters: Map<PetPose, Raster> by lazy {
        mapOf(
            PetPose.Sit to BirdSprites.sit.toRaster(),
            PetPose.Stand to BirdSprites.stand.toRaster(),
            PetPose.Lie to BirdSprites.lie.toRaster(),
        )
    }

    override fun DrawScope.draw(frame: PetFrame) {
        val step = frame.step
        val cell = pix.toFloat()

        // Roam runs outside the pill on the no-hole scene, using BirdRoam key-table sprites.
        if (frame.out != null) {
            val from = step.roam?.hurryFrom ?: 0f
            val t = from + (1f - from) * frame.progress
            val face = if (frame.face == 0f) step.face.toFloat() else frame.face
            with(BirdRoam) {
                draw(t, face < 0f, left(frame.x), top, cell) { pose -> rigRasters.getValue(pose) }
            }
            return
        }

        val ox = left(frame.x)
        val oy = top
        val mirror = (if (frame.face == 0f) step.face.toFloat() else frame.face) < 0f

        clipPath(holePath, ClipOp.Difference) {
            when (frame.state) {
                PetState.Sit -> drawSit(frame, ox, oy, cell, mirror)
                PetState.Sleep -> drawSleep(frame, ox, oy, cell, mirror)
                PetState.Walk -> drawWalk(frame, ox, oy, cell, mirror)
                PetState.Hide -> drawHide(frame, oy, cell)
                PetState.Peek -> drawPeek(frame, ox, oy, cell)
                PetState.Hidden -> drawHidden(frame, ox, oy, cell)
                PetState.Dance -> drawDance(frame, ox, oy, cell, mirror)
                else -> drawAction(frame, ox, oy, cell, mirror)
            }
            drawMarks(frame, ox, oy, cell, mirror)
        }
    }

    private fun DrawScope.drawSit(
        frame: PetFrame,
        ox: Float,
        oy: Float,
        cell: Float,
        mirror: Boolean,
    ) {
        val step = frame.step
        val blend = frame.blend
        if (blend < 1f && (step.poseFrom != PetPose.Sit || step.faceFrom != step.face)) {
            if (step.faceFrom != step.face && abs(frame.face) < 0.35f) {
                drawPicture(BirdSprites.lookFront, mirror, ox, oy, cell)
                return
            }
            if (step.poseFrom != PetPose.Sit) {
                drawPicture(transitionSprite(step.poseFrom, PetPose.Sit, blend), mirror, ox, oy, cell)
                return
            }
        }
        val pic =
            when {
                frame.blink -> BirdSprites.sitBlink
                frame.low -> BirdSprites.sitLow
                else -> BirdSprites.sit
            }
        drawPicture(pic, mirror, ox, oy, cell)
    }

    private fun DrawScope.drawSleep(
        frame: PetFrame,
        ox: Float,
        oy: Float,
        cell: Float,
        mirror: Boolean,
    ) {
        val step = frame.step
        val blend = frame.blend
        if (blend < 1f && step.poseFrom != PetPose.Lie) {
            drawPicture(transitionSprite(step.poseFrom, PetPose.Lie, blend), mirror, ox, oy, cell)
            return
        }
        val z = frame.mark(PetMark.Z)
        val pic = if (z in 0.15f..0.75f) BirdSprites.lieBreath else BirdSprites.lie
        drawPicture(pic, mirror, ox, oy, cell)
    }

    private fun DrawScope.drawWalk(
        frame: PetFrame,
        ox: Float,
        oy: Float,
        cell: Float,
        mirror: Boolean,
    ) {
        val step = frame.step
        val blend = frame.blend
        // PetMachine keeps x at fromX for the first PET_BLEND_MS: turn, dip eagerly, and lean into the first stride.
        if (frame.ms < PET_BLEND_MS) {
            if (step.faceFrom != step.face && abs(frame.face) < 0.35f) {
                drawPicture(BirdSprites.lookFront, mirror, ox, oy, cell)
                return
            }
            val pic =
                when {
                    step.poseFrom == PetPose.Lie && blend < 0.45f -> BirdSprites.transLie
                    blend < 0.25f -> basePicture(step.poseFrom)
                    blend < 0.58f -> BirdSprites.stand
                    else -> BirdSprites.walk[0]
                }
            val dy = if (blend in 0.30f..0.58f) 0.7f * sin(((blend - 0.30f) / 0.28f) * PI.toFloat()) else 0f
            val lean = if (blend >= 0.58f) 6f * ease((blend - 0.58f) / 0.42f) else 0f
            drawPicture(pic, mirror, ox, oy, cell, pinTargetY = 19f + dy, turnDeg = lean)
            return
        }
        // Settle cleanly onto stand at the very end of the walk.
        if (frame.progress > 0.94f) {
            drawPicture(BirdSprites.stand, mirror, ox, oy, cell)
            return
        }
        val walked = abs(frame.x - step.fromX) * span / pix
        val stride = walked / 1.85f
        val idx = (floor(stride * 4f).toInt() and 3)
        // Subtle head-bob bounce locked to pass frames, slightly offset from legs so the loop stays organic.
        val bob = if (idx == 1 || idx == 3) -0.5f else 0f
        drawPicture(BirdSprites.walk[idx], mirror, ox, oy, cell, pinTargetY = 19f + bob)
    }

    /**
     * Flutter-runs to the camera hole at full size and stops behind it: the hole's cutout covers the middle of the body.
     * It ends on the pose [drawHidden] shows, so the hidden bird stands exactly where the run stopped.
     */
    private fun DrawScope.drawHide(
        frame: PetFrame,
        oy: Float,
        cell: Float,
    ) {
        val step = frame.step
        val t = frame.progress
        val mirror = step.face < 0
        val startLeft = left(step.fromX)
        val endLeft = left(step.toX)
        if (t >= 0.9f) {
            drawPicture(BirdSprites.stand, mirror, endLeft, oy, cell)
            return
        }
        val u = t / 0.9f
        val sprite = if ((frame.ms / 70L) % 2L == 0L) BirdSprites.hideRun0 else BirdSprites.hideRun1
        // Three hops that land exactly on the ground at the end of the run.
        val hop = -abs(sin(u * 3f * PI.toFloat())) * cell * 1.9f
        drawPicture(sprite, mirror, lerp(startLeft, endLeft, ease(u)), oy + hop, cell, turnDeg = 8f * (1f - u))
    }

    /** Stands still behind the hole; drawn once, so it costs no frames. */
    private fun DrawScope.drawHidden(
        frame: PetFrame,
        ox: Float,
        oy: Float,
        cell: Float,
    ) = drawPicture(BirdSprites.stand, frame.step.face < 0, ox, oy, cell)

    /**
     * Cranes its neck out to the side of the hole, with its feet still behind it, looks around, then draws back to the
     * hidden stand. The bird keeps full size and never looks over the top of the hole.
     */
    private fun DrawScope.drawPeek(
        frame: PetFrame,
        ox: Float,
        oy: Float,
        cell: Float,
    ) {
        val t = frame.progress
        val dir = if (frame.step.face < 0) -1f else 1f
        val holeCells = (hole?.width ?: (box * 0.3f)) / 2f / cell
        // The head must clear the rim by its own half width (4.5 cells). Leaning 30 degrees moves it 5.5 cells; the rest is a shift.
        val lean = 30f
        val extra = max(0f, holeCells + 4.5f - 5.5f - 0f) * cell
        val out =
            when {
                t < 0.22f -> ease(t / 0.22f)
                t < 0.72f -> 1f
                else -> 1f - ease((t - 0.72f) / 0.28f)
            }
        val sway = if (t in 0.22f..0.72f) 0.1f * sin(frame.ms / 260f) else 0f
        val sprite = if (t in 0.4f..0.55f) BirdSprites.lookFront else BirdSprites.stand
        val shift = dir * extra * out
        drawPicture(sprite, dir < 0f, ox + shift, oy, cell, turnDeg = lean * (out + sway))
    }

    /** Seamless 2-beat (1000ms) party-bird groove: bobs on every beat with alternating wing pops and joyful chirps. */
    private fun DrawScope.drawDance(
        frame: PetFrame,
        ox: Float,
        oy: Float,
        cell: Float,
        mirror: Boolean,
    ) {
        val twoBeatMs = PET_BEAT_MS * 2L
        val phase = (frame.ms % twoBeatMs).toFloat() / twoBeatMs
        val beat = frame.beat
        val bounce = sin(beat * PI.toFloat())
        val sway = sin(phase * 2f * PI.toFloat())
        val sprite =
            when {
                phase < 0.22f -> BirdSprites.danceDownR
                phase < 0.50f -> BirdSprites.danceUpR
                phase < 0.72f -> BirdSprites.danceDownL
                else -> BirdSprites.danceUpL
            }
        drawPicture(
            sprite,
            mirror,
            ox,
            oy,
            cell,
            pinTargetX = 10f + sway * 1.4f,
            pinTargetY = 19f + 0.7f - 2.3f * bounce,
            turnDeg = sway * 7f,
        )
    }

    private fun DrawScope.drawAction(
        frame: PetFrame,
        ox: Float,
        oy: Float,
        cell: Float,
        mirror: Boolean,
    ) {
        val action = birdActionFor(frame.state)
        if (action == null) {
            drawPicture(basePicture(frame.state.pose), mirror, ox, oy, cell)
            return
        }
        val step = frame.step
        val t = frame.progress
        // Smooth wake from Lie into an upright action before the action takes over.
        if (step.poseFrom == PetPose.Lie && frame.state != PetState.Tired && t < 0.12f) {
            val pic = if (t < 0.05f) BirdSprites.lie else BirdSprites.transLie
            drawPicture(pic, mirror, ox, oy, cell)
            return
        }
        with(action) {
            draw(t, mirror, ox, oy, cell) { pose -> rigRasters.getValue(pose) }
        }
    }

    private fun transitionSprite(
        from: PetPose,
        to: PetPose,
        u: Float,
    ): Picture =
        when {
            u < 0.25f -> basePicture(from)
            u > 0.75f -> basePicture(to)
            from == PetPose.Lie || to == PetPose.Lie -> BirdSprites.transLie
            else -> BirdSprites.stand
        }

    private fun basePicture(pose: PetPose): Picture =
        when (pose) {
            PetPose.Sit -> BirdSprites.sit
            PetPose.Stand -> BirdSprites.stand
            PetPose.Lie -> BirdSprites.lie
        }

    /** Draws [pic] aligned to the 20x20 grid at ([ox], [oy]), optionally shifted or turned around its pin. */
    private fun DrawScope.drawPicture(
        pic: Picture,
        mirror: Boolean,
        ox: Float,
        oy: Float,
        cell: Float,
        pinTargetX: Float = pic.pinX.toFloat(),
        pinTargetY: Float = pic.pinY.toFloat(),
        turnDeg: Float = 0f,
    ) {
        fun sx(i: Int) = (ox + i * cell).roundToInt().toFloat()

        fun sy(j: Int) = (oy + j * cell).roundToInt().toFloat()

        if (abs(turnDeg) < 0.5f) {
            val dx = (pinTargetX - pic.pinX).roundToInt()
            val dy = (pinTargetY - pic.pinY).roundToInt()
            for (j in 0 until pic.h) {
                var i = 0
                while (i < pic.w) {
                    val col = pic.c[j * pic.w + i]
                    if (col == 0) {
                        i++
                        continue
                    }
                    var end = i
                    while (end + 1 < pic.w && pic.c[j * pic.w + end + 1] == col) end++
                    val a = if (mirror) GRID - 1 - (end + dx) else i + dx
                    val b = if (mirror) GRID - (i + dx) else end + dx + 1
                    val gy = j + dy
                    drawRect(Color(col), Offset(sx(a), sy(gy)), Size(sx(b) - sx(a), sy(gy + 1) - sy(gy)))
                    i = end + 1
                }
            }
            return
        }

        val px = pinTargetX + 0.5f
        val py = pinTargetY + 0.5f
        val rad = turnDeg * PI.toFloat() / 180f
        val cs = cos(rad)
        val sn = sin(rad)
        val reach = hypot(pic.w.toFloat(), pic.h.toFloat()) + 1f
        for (j in floor(py - reach).toInt()..ceil(py + reach).toInt()) {
            for (i in floor(px - reach).toInt()..ceil(px + reach).toInt()) {
                val dx = i + 0.5f - px
                val dy = j + 0.5f - py
                val ix = floor(pic.pinX + 0.5f + dx * cs + dy * sn).toInt()
                val iy = floor(pic.pinY + 0.5f - dx * sn + dy * cs).toInt()
                if (ix !in 0 until pic.w || iy !in 0 until pic.h) continue
                val col = pic.c[iy * pic.w + ix]
                if (col == 0) continue
                val gx = if (mirror) GRID - 1 - i else i
                drawRect(Color(col), Offset(sx(gx), sy(j)), Size(sx(gx + 1) - sx(gx), sy(j + 1) - sy(j)))
            }
        }
    }

    private fun DrawScope.drawMarks(
        frame: PetFrame,
        ox: Float,
        oy: Float,
        cell: Float,
        mirror: Boolean,
    ) {
        val marks =
            buildList {
                val hx = if (frame.state == PetState.Sleep) 13f else 11f
                val hy = if (frame.state == PetState.Sleep) 13f else 7f
                val heart = frame.mark(PetMark.Heart)
                if (heart >= 0f && frame.state != PetState.Excited) {
                    val small = heart < 0.12f
                    val alpha = 1f - ease((heart - 0.62f) / 0.38f)
                    val xOff = if (frame.state == PetState.Excited) 5.5f else 4.2f
                    val x = hx + xOff + 1.1f * sin(heart * 9f) - if (small) 1f else 3f
                    // Keep the full rising heart cleanly inside the pill's top border.
                    val startY = if (frame.state == PetState.Excited) hy - 7.0f else hy - 4.8f
                    add(Mark(if (small) BIRD_HEART_SM else BIRD_HEART, x, startY - 4.6f * ease(heart), alpha))
                }
                val z = frame.mark(PetMark.Z)
                if (z >= 0f) {
                    for (i in 0..2) {
                        val q = (z - i * 0.2f) / 0.6f
                        if (q <= 0f || q >= 1f) continue
                        val alpha = min(1f, q * 5f) * (1f - ease((q - 0.55f) / 0.45f))
                        add(Mark(if (i == 0) BIRD_Z_SM else BIRD_Z_BIG, hx + 1.5f + q * 3f + sin(q * 6f), hy - 2.2f - q * 6.5f, alpha))
                    }
                }
                val sweat = frame.mark(PetMark.Sweat)
                if (sweat >= 0f) {
                    val q = (sweat * 3f) % 1f
                    add(Mark(BIRD_DROP, hx - 7.2f, hy - 1.5f + q * 4f, bump(q, 0f, 1f) * 1.4f))
                }
                if (frame.low && (frame.state == PetState.Tired || frame.state == PetState.Sleep)) {
                    add(Mark(BIRD_BATTERY, 0f, 0f, 1f))
                }
                if (frame.state == PetState.Excited) {
                    val fade = 1f - ease((frame.progress - 0.85f) / 0.15f)
                    add(Mark(BIRD_BOLT, 0f, 0.5f + wave(frame.ms, 600), fade))
                    for (k in 0..2) {
                        val a = frame.ms / 400f + k * 2.1f
                        add(
                            Mark(
                                BIRD_SPARK,
                                9f + 8.5f * cos(a),
                                7f + 5f * sin(a),
                                fade * bump(((frame.ms + k * 230) % 700) / 700f, 0f, 1f),
                            ),
                        )
                    }
                }
                if (frame.state == PetState.Startle && frame.progress < 0.55f) {
                    add(Mark(BIRD_BANG, hx + 6f, hy - 6f, 1f))
                }
                if (frame.state == PetState.Peck) {
                    val t = frame.progress
                    for (hit in floatArrayOf(0.24f, 0.52f, 0.78f)) {
                        val dt = t - hit
                        if (dt in 0f..0.11f) {
                            val u = dt / 0.11f
                            add(Mark(BIRD_CRUMB, 16.5f + u * 1.5f, 17f - sin(u * PI.toFloat()) * 3f, 1f - u))
                        }
                    }
                }
            }
        val dot = max(1, cell.roundToInt()).toFloat()
        for (m in marks) {
            if (m.alpha <= 0f) continue
            val width = m.rows.maxOf { it.length }
            val gx = if (mirror) GRID - m.x - width else m.x
            m.rows.forEachIndexed { rj, line ->
                line.forEachIndexed { ri, ch ->
                    if (ch != '.') {
                        val color = Color(birdMarkColor(ch)).copy(alpha = m.alpha.coerceIn(0f, 1f))
                        val rx = (ox + (gx + ri) * cell).roundToInt().toFloat()
                        val ry = (oy + (m.y + rj) * cell).roundToInt().toFloat()
                        drawRect(color, Offset(rx, ry), Size(dot, dot))
                    }
                }
            }
        }
    }
}

/** Lookup of key-table actions defined in PixelBirdActions.kt. */
internal fun birdActionFor(state: PetState): PixelAction? = PixelBirdActions.byState[state]
