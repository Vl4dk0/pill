private fun birdMarkColor(ch: Char): Int =
    when (ch) {
        'R' -> 0xFFFF4D6D.toInt()
        'r' -> 0xFFFFB3C1.toInt()
        'W' -> 0xFFE6F0FF.toInt()
        'B' -> 0xFF7FD0FF.toInt()
        'Y' -> 0xFFFFD43B.toInt()
        else -> 0xFFFFFFFF.toInt()
    }

internal fun birdPic(
    name: String,
    rows: String,
): Picture = PixelSprite(name, rows).picture(BIRD_PALETTE)

/** Converts a 20x20 [Picture] to a [Raster] for [PixelAction] built-in poses (`sit`, `stand`, `lie`). */
private fun Picture.toRaster(): Raster =
    Raster().also { r ->
        for (j in 0 until min(h, GRID)) {
            for (i in 0 until min(w, GRID)) {
                r.c[j * GRID + i] = c[j * w + i]
            }
        }
    }

